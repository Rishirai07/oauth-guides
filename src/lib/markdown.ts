import { sourceLabel } from "./format";
import { CONFIDENCE_LABEL, DIFFICULTY_LABEL, OWNER_LABEL, type Guide } from "./types";

export function guideToMarkdown(g: Guide): string {
  const L: string[] = [];
  const src = (ids?: number[]) => (ids?.length ? " " + ids.map((i) => `[${i}]`).join("") : "");
  L.push(`# ${g.name}: OAuth app setup and approval`);
  L.push("");
  L.push(`> ${g.tagline}`);
  L.push("");
  L.push(`**Difficulty: ${DIFFICULTY_LABEL[g.verdict.difficulty]}.** ${g.verdict.headline}`);
  L.push("");
  L.push(g.verdict.why);
  L.push("");
  L.push(`| | |`);
  L.push(`|---|---|`);
  L.push(`| Hands-on work | ${g.effort.handsOn} |`);
  L.push(`| Waiting for approval | ${g.effort.approvalWait} |`);
  L.push(`| First test connection | ${g.effort.timeToFirstConnection} |`);
  L.push(`| Production-ready | ${g.effort.timeToProduction} |`);
  L.push(`| Cost | ${g.effort.cost} |`);
  L.push("");
  if (g.modes.length) {
    L.push(`## Ways your app can exist`);
    for (const m of g.modes) L.push(`- **${m.name}.** ${m.whatYouGet} Limits: ${m.limits} Review: ${m.reviewNeeded}`);
    L.push("");
  }
  if (g.prerequisites.length) {
    L.push(`## Before you start`);
    for (const p of g.prerequisites) L.push(`- ${p.item}${p.required ? "" : " (optional)"}: ${p.why}`);
    L.push("");
  }
  L.push(`## Steps`);
  g.phases.forEach((ph, i) => {
    L.push(`### ${i + 1}. ${ph.title}`);
    L.push(`_${ph.goal}_`);
    L.push("");
    for (const s of ph.steps) {
      L.push(`- [ ] **${s.title}** (${OWNER_LABEL[s.owner]}${s.time ? `, ~${s.time}` : ""}; ${CONFIDENCE_LABEL[s.confidence]})${src(s.sourceIds)}`);
      L.push(`  ${s.detail}`);
      for (const l of s.links || []) L.push(`  ${l}`);
    }
    L.push("");
  });
  L.push(`## Approval`);
  L.push(`- Required: ${{ no: "no", conditional: "for some uses", yes: "yes" }[g.approval.required]}`);
  L.push(`- Triggered by: ${g.approval.trigger}`);
  if (g.approval.process.length) L.push(`- Process: ${g.approval.process.join(" → ")}`);
  L.push(`- Typical wait: ${g.approval.typicalWait} (${CONFIDENCE_LABEL[g.approval.confidence].toLowerCase()})`);
  L.push("");
  if (g.gotchas.length) {
    L.push(`## Gotchas`);
    for (const x of g.gotchas) L.push(`- **${x.title}.** ${x.detail} _(${x.impact} impact, ${CONFIDENCE_LABEL[x.confidence].toLowerCase()})_${src(x.sourceIds)}`);
    L.push("");
  }
  if (g.blockers.length) {
    L.push(`## If you get stuck`);
    for (const b of g.blockers) L.push(`- \`${b.symptom}\`: ${b.cause} Fix: ${b.fix}`);
    L.push("");
  }
  L.push(`## What an agent can do, and what you have to do`);
  L.push(`An agent can:`);
  for (const a of g.handoff.agentCan) L.push(`- ${a}`);
  L.push("");
  L.push(`You have to:`);
  for (const a of g.handoff.youMust) L.push(`- ${a}`);
  L.push("");
  const o = Object.entries(g.oauth).filter(([, v]) => v);
  if (o.length) {
    L.push(`## OAuth reference`);
    for (const [k, v] of o) L.push(`- **${k}:** ${v}`);
    L.push("");
  }
  L.push(`## Evidence`);
  if (g.tested.length) {
    L.push(`Live checks:`);
    for (const t of g.tested) L.push(`- ${t.ok ? "OK" : "Failed"}: ${t.check}. ${t.result} (${t.at.slice(0, 10)})`);
  } else {
    L.push(`No live checks recorded yet.`);
  }
  if (g.uncertain.length) {
    L.push("");
    L.push(`Not verified yet:`);
    for (const u of g.uncertain) L.push(`- ${u}`);
  }
  if (g.reviewNotes?.length) {
    L.push("");
    L.push(`Corrected during research:`);
    for (const u of g.reviewNotes) L.push(`- ${u}`);
  }
  L.push("");
  L.push(`Sources:`);
  for (const s of g.sources) L.push(`${s.id}. [${sourceLabel(s)}](${s.url})${s.kind === "official" ? "" : " (third-party)"}`);
  L.push("");
  L.push(`_${g.origin === "curated" ? "Researched by hand" : "Generated by the research agent, not reviewed by a person"}. Last updated ${g.updatedAt.slice(0, 10)}._`);
  return L.join("\n");
}
