import type { Guide } from "@/lib/types";
import { ConfidenceChip, DifficultyMeter, OwnerChip } from "./badges";
import { GuideActions } from "./GuideActions";
import { ProbePanel } from "./ProbePanel";
import { sourceLabel } from "@/lib/format";

function Section({ id, title, kicker, children }: { id: string; title: string; kicker?: string; children: React.ReactNode }) {
  return (
    <section id={id} className="scroll-mt-20 border-t border-line pt-8">
      <div className="mb-4">
        {kicker && <p className="text-[11px] uppercase tracking-[0.14em] text-muted font-semibold">{kicker}</p>}
        <h2 className="text-xl font-semibold tracking-tight">{title}</h2>
      </div>
      {children}
    </section>
  );
}

function SrcRefs({ ids }: { ids?: number[] }) {
  if (!ids?.length) return null;
  return (
    <span className="ml-1 text-xs">
      {ids.map((i) => (
        <a key={i} href={`#src-${i}`} className="text-accent hover:underline mr-0.5">[{i}]</a>
      ))}
    </span>
  );
}

const IMPACT: Record<string, string> = {
  high: "border-l-red-600",
  medium: "border-l-amber-500",
  low: "border-l-stone-300",
};

export function GuideView({ guide: g, shareUrl, canProbe = false }: { guide: Guide; shareUrl?: string; canProbe?: boolean }) {
  const stepCount = g.phases.reduce((n, p) => n + p.steps.length, 0);
  const agentSteps = g.phases.reduce((n, p) => n + p.steps.filter((s) => s.owner !== "you").length, 0);
  const toc = [
    ["verdict", "Verdict"],
    ["effort", "Time and effort"],
    ["modes", "App modes"],
    ["prereqs", "Before you start"],
    ["steps", "Steps"],
    ["approval", "Approval"],
    ["gotchas", "Gotchas"],
    ["blockers", "If you get stuck"],
    ["handoff", "Agent or you"],
    ["oauth", "OAuth reference"],
    ["evidence", "Evidence"],
  ];

  return (
    <article className="mx-auto max-w-6xl px-5 py-10">
      <header className="mb-8">
        <div className="flex flex-wrap items-center gap-2 text-xs text-muted mb-3">
          <span className="rounded-full border border-line px-2 py-0.5">{g.category}</span>
          {g.origin === "curated" ? (
            <span className="rounded-full bg-ink text-paper px-2 py-0.5">Curated, checked against sources</span>
          ) : (
            <span className="rounded-full bg-violet-700 text-white px-2 py-0.5">Generated by the research agent{g.model ? ` (${g.model})` : ""}</span>
          )}
          <span>Updated {g.updatedAt.slice(0, 10)}</span>
          {g.website && (
            <a href={g.website} target="_blank" rel="noreferrer" className="hover:text-ink underline">{g.website.replace(/^https?:\/\//, "")}</a>
          )}
        </div>
        <h1 className="text-3xl md:text-4xl font-semibold tracking-tight">{g.name} <span className="block md:inline text-muted font-normal md:ml-2 text-2xl md:text-4xl">OAuth setup and approval</span></h1>
        <p className="mt-3 text-lg text-muted max-w-3xl">{g.tagline}</p>
        <div className="mt-5"><GuideActions guide={g} shareUrl={shareUrl} /></div>
      </header>

      <div className="grid lg:grid-cols-[1fr_260px] gap-10">
        <div className="space-y-10 min-w-0">
          <section id="verdict" className="scroll-mt-20 rounded-xl border border-line bg-card p-6">
            <DifficultyMeter d={g.verdict.difficulty} size="lg" />
            <p className="mt-3 text-xl font-semibold leading-snug">{g.verdict.headline}</p>
            <p className="mt-2 text-[15px] leading-relaxed text-ink/80">{g.verdict.why}</p>
          </section>

          <Section id="effort" title="Time and effort">
            <div className="grid sm:grid-cols-2 md:grid-cols-3 gap-3">
              {[
                ["Hands-on work", g.effort.handsOn],
                ["Waiting for approval", g.effort.approvalWait],
                ["First test connection", g.effort.timeToFirstConnection],
                ["Production-ready", g.effort.timeToProduction],
                ["Cost", g.effort.cost],
              ].map(([k, v]) => (
                <div key={k} className={`rounded-lg border border-line bg-card p-4 ${k === "Waiting for approval" ? "ring-2 ring-accent/30" : ""}`}>
                  <p className="text-[11px] uppercase tracking-wider text-muted font-semibold">{k}</p>
                  <p className="mt-1 text-[15px] leading-snug">{v}</p>
                </div>
              ))}
            </div>
          </Section>

          {g.modes.length > 0 && (
            <Section id="modes" title="Ways your app can exist" kicker="Test, unlisted, reviewed">
              <div className="overflow-x-auto rounded-lg border border-line bg-card">
                <table className="w-full text-sm">
                  <thead className="text-left text-[11px] uppercase tracking-wider text-muted">
                    <tr className="border-b border-line">
                      <th className="p-3">Mode</th><th className="p-3">What you get</th><th className="p-3">Limits</th><th className="p-3">Review</th>
                    </tr>
                  </thead>
                  <tbody>
                    {g.modes.map((m, i) => (
                      <tr key={i} className="border-b border-line last:border-0 align-top">
                        <td className="p-3 font-medium">{m.name}</td>
                        <td className="p-3">{m.whatYouGet}</td>
                        <td className="p-3 text-ink/80">{m.limits}</td>
                        <td className="p-3">{m.reviewNeeded}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </Section>
          )}

          {g.prerequisites.length > 0 && (
            <Section id="prereqs" title="Before you start">
              <ul className="space-y-2">
                {g.prerequisites.map((p, i) => (
                  <li key={i} className="flex gap-3">
                    <span className={`mt-0.5 shrink-0 rounded px-1.5 py-0.5 text-[10px] font-bold uppercase ${p.required ? "bg-ink text-paper" : "bg-line text-muted"}`}>{p.required ? "Required" : "Optional"}</span>
                    <span><span className="font-medium">{p.item}.</span> <span className="text-ink/75">{p.why}</span></span>
                  </li>
                ))}
              </ul>
            </Section>
          )}

          <Section id="steps" title={`Steps (${stepCount})`} kicker={stepCount ? `An agent can do or draft ${agentSteps} of these` : undefined}>
            {stepCount === 0 && <p className="text-muted">No steps were produced for this app. Check the sources below.</p>}
            <ol className="space-y-8">
              {g.phases.map((ph, i) => (
                <li key={i}>
                  <div className="flex items-baseline gap-3">
                    <span className="font-mono text-sm text-accent">{String(i + 1).padStart(2, "0")}</span>
                    <div>
                      <h3 className="font-semibold text-lg">{ph.title}</h3>
                      <p className="text-sm text-muted">{ph.goal}</p>
                    </div>
                  </div>
                  <ul className="mt-3 ml-7 border-l border-line pl-5 space-y-4">
                    {ph.steps.map((s, j) => (
                      <li key={j} className="relative">
                        <span className="absolute -left-[26px] top-1.5 size-2.5 rounded-full bg-paper ring-2 ring-ink/40" />
                        <div className="flex flex-wrap items-center gap-2">
                          <span className="font-medium">{s.title}</span>
                          <OwnerChip o={s.owner} />
                          {s.time && <span className="text-xs text-muted">~{s.time}</span>}
                        </div>
                        <p className="mt-1 text-[15px] leading-relaxed text-ink/85">{s.detail}<SrcRefs ids={s.sourceIds} /></p>
                        <div className="mt-1.5 flex flex-wrap items-center gap-2">
                          <ConfidenceChip c={s.confidence} />
                          {s.links?.map((l, k) => (
                            <a key={k} href={l} target="_blank" rel="noreferrer" className="text-xs text-accent hover:underline break-all">{l.replace(/^https?:\/\//, "")} ↗</a>
                          ))}
                        </div>
                      </li>
                    ))}
                  </ul>
                </li>
              ))}
            </ol>
          </Section>

          <Section id="approval" title="Approval">
            <div className="rounded-lg border border-line bg-card p-5">
              <div className="flex flex-wrap items-center gap-3">
                <span className={`rounded-md px-2.5 py-1 text-sm font-semibold ${g.approval.required === "no" ? "bg-emerald-100 text-emerald-800" : g.approval.required === "yes" ? "bg-red-100 text-red-800" : "bg-amber-100 text-amber-800"}`}>
                  {g.approval.required === "no" ? "No review required" : g.approval.required === "yes" ? "Review required" : "Review required for some uses"}
                </span>
                <ConfidenceChip c={g.approval.confidence} />
              </div>
              <p className="mt-3"><span className="font-medium">Triggered by: </span>{g.approval.trigger}</p>
              {g.approval.process.length > 0 && (
                <ol className="mt-3 flex flex-wrap items-center gap-2 text-sm">
                  {g.approval.process.map((p, i) => (
                    <li key={i} className="flex items-center gap-2">
                      <span className="rounded-md border border-line px-2 py-1">{p}</span>
                      {i < g.approval.process.length - 1 && <span className="text-muted">→</span>}
                    </li>
                  ))}
                </ol>
              )}
              <p className="mt-3"><span className="font-medium">Typical wait: </span>{g.approval.typicalWait}</p>
            </div>
          </Section>

          {g.gotchas.length > 0 && (
            <Section id="gotchas" title="Gotchas">
              <div className="space-y-3">
                {g.gotchas.map((x, i) => (
                  <div key={i} className={`rounded-lg border border-line border-l-4 ${IMPACT[x.impact]} bg-card p-4`}>
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="font-semibold">{x.title}</span>
                      <span className="text-[11px] uppercase tracking-wider text-muted">{x.impact} impact</span>
                      <ConfidenceChip c={x.confidence} />
                    </div>
                    <p className="mt-1 text-[15px] text-ink/85">{x.detail}<SrcRefs ids={x.sourceIds} /></p>
                  </div>
                ))}
              </div>
            </Section>
          )}

          {g.blockers.length > 0 && (
            <Section id="blockers" title="If you get stuck">
              <div className="space-y-2">
                {g.blockers.map((b, i) => (
                  <details key={i} className="rounded-lg border border-line bg-card p-4 group">
                    <summary className="cursor-pointer font-mono text-sm">{b.symptom}</summary>
                    <p className="mt-2 text-sm"><span className="text-muted">Cause:</span> {b.cause}</p>
                    <p className="mt-1 text-sm"><span className="text-muted">Fix:</span> {b.fix}</p>
                  </details>
                ))}
              </div>
            </Section>
          )}

          <Section id="handoff" title="What an agent can do, and where you take over">
            <div className="grid md:grid-cols-2 gap-4">
              <div className="rounded-lg border border-violet-200 bg-violet-50/50 p-5">
                <p className="font-semibold text-violet-900">An agent can</p>
                <ul className="mt-2 space-y-1.5 text-[15px] list-disc pl-5">{g.handoff.agentCan.map((a, i) => <li key={i}>{a}</li>)}</ul>
              </div>
              <div className="rounded-lg border border-ink/20 bg-card p-5">
                <p className="font-semibold">You must</p>
                <ul className="mt-2 space-y-1.5 text-[15px] list-disc pl-5">{g.handoff.youMust.map((a, i) => <li key={i}>{a}</li>)}</ul>
              </div>
            </div>
          </Section>

          {Object.keys(g.oauth).length > 0 && (
            <Section id="oauth" title="OAuth reference">
              <dl className="rounded-lg border border-line bg-card divide-y divide-line text-sm">
                {Object.entries(g.oauth).filter(([, v]) => v).map(([k, v]) => (
                  <div key={k} className="grid sm:grid-cols-[180px_1fr] gap-1 p-3">
                    <dt className="text-muted">{k.replace(/([A-Z])/g, " $1").replace(/^./, (c) => c.toUpperCase())}</dt>
                    <dd className={/^https?:/.test(v as string) ? "font-mono text-xs break-all" : ""}>{v as string}</dd>
                  </div>
                ))}
              </dl>
            </Section>
          )}

          <Section id="evidence" title="Evidence">
            <div className="space-y-6">
              <div className="rounded-lg border border-line bg-card p-5">
                <p className="font-semibold mb-3">Live checks against the provider</p>
                <ProbePanel slug={g.slug} initial={g.tested} canRun={canProbe} />
              </div>
              {g.reviewNotes && g.reviewNotes.length > 0 && (
                <div className="rounded-lg border border-line bg-card p-5">
                  <p className="font-semibold mb-2">Corrected during research</p>
                  <ul className="list-disc pl-5 space-y-1 text-sm">{g.reviewNotes.map((n, i) => <li key={i}>{n}</li>)}</ul>
                </div>
              )}
              {g.uncertain.length > 0 && (
                <div className="rounded-lg border border-amber-200 bg-amber-50/60 p-5">
                  <p className="font-semibold mb-2 text-amber-900">Not verified yet</p>
                  <ul className="list-disc pl-5 space-y-1 text-sm">{g.uncertain.map((n, i) => <li key={i}>{n}</li>)}</ul>
                </div>
              )}
              <div>
                <p className="font-semibold mb-2">Sources</p>
                <ol className="space-y-1.5 text-sm">
                  {g.sources.map((s) => (
                    <li key={s.id} id={`src-${s.id}`} className="scroll-mt-20 flex gap-2">
                      <span className="font-mono text-muted w-7 shrink-0">[{s.id}]</span>
                      <span>
                        <a href={s.url} target="_blank" rel="noreferrer" className="hover:underline">{sourceLabel(s)}</a>
                        <span className={`ml-2 text-[10px] uppercase tracking-wider ${s.kind === "official" ? "text-sky-700" : "text-amber-700"}`}>{s.kind === "official" ? "official" : "third-party"}</span>
                      </span>
                    </li>
                  ))}
                </ol>
              </div>
            </div>
          </Section>
        </div>

        <aside className="no-print hidden lg:block">
          <div className="sticky top-20 space-y-5">
            <div className="rounded-lg border border-line bg-card p-4 text-sm space-y-2">
              <DifficultyMeter d={g.verdict.difficulty} />
              <p><span className="text-muted">Work:</span> {g.effort.handsOn}</p>
              <p><span className="text-muted">Wait:</span> {g.effort.approvalWait}</p>
              <p><span className="text-muted">Agent can help with:</span> {agentSteps} of {stepCount} steps</p>
            </div>
            <nav className="text-sm space-y-1">
              {toc.map(([id, label]) => (
                <a key={id} href={`#${id}`} className="block text-muted hover:text-ink">{label}</a>
              ))}
            </nav>
            <div className="text-[11px] text-muted space-y-1">
              <p className="font-semibold uppercase tracking-wider">Confidence key</p>
              <div className="flex flex-col gap-1 items-start">
                <ConfidenceChip c="tested" /><ConfidenceChip c="documented" /><ConfidenceChip c="community" /><ConfidenceChip c="inferred" />
              </div>
            </div>
          </div>
        </aside>
      </div>
    </article>
  );
}
